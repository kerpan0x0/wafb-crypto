import { describe, it, expect, vi, afterEach } from 'vitest';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { generateHybridIdentity, generateX25519Identity, identityToRecipient } from 'age-encryption';
import {
  validateRecipient,
  computeKeyId,
  formatKeyId,
  keyIdMatches,
  RecipientError,
  recipientStateFromInput,
  confirmRecipient,
  KeyIdMismatchError,
  KEY_ID_DOMAIN,
} from '../../../src/protection/recipient';
import {
  createInvite,
  parseInvite,
  inviteFromHash,
  inviteUrl,
  generateCaseRef,
  InviteError,
} from '../../../src/protection/invite';
import { hasTool } from '../../helpers/independent-tools';

const HAVE_AGE_KEYGEN = hasTool('age-keygen');

async function freshRecipient() {
  return identityToRecipient(await generateX25519Identity());
}

afterEach(() => vi.restoreAllMocks());

describe('validateRecipient (RF1)', () => {
  it('accepts an X25519 recipient and computes the documented key ID', async () => {
    const r = await freshRecipient();
    const v = await validateRecipient(r);
    expect(v.type).toBe('age-x25519');
    expect(v.canonical).toBe(r);
    const expected = createHash('sha256').update(KEY_ID_DOMAIN + r, 'utf8').digest('hex');
    expect(v.keyId).toBe(expected);
    expect(v.keyId).toMatch(/^[0-9a-f]{64}$/);
  });

  it.skipIf(!HAVE_AGE_KEYGEN)('accepts a recipient generated by the reference age-keygen', async () => {
    const out = execFileSync('age-keygen').toString();
    const pub = /public key: (age1[0-9a-z]+)/.exec(out)![1];
    expect((await validateRecipient(pub)).canonical).toBe(pub);
  });

  it('maps the upper-case and whitespace-padded forms to the same key ID', async () => {
    const r = await freshRecipient();
    const a = await validateRecipient(r);
    const b = await validateRecipient(`  ${r.toUpperCase()}\n`);
    expect(b.canonical).toBe(a.canonical);
    expect(b.keyId).toBe(a.keyId);
  });

  it('rejects a private identity WITHOUT echoing it in the error or in any log', async () => {
    const secret = await generateX25519Identity();
    const spies = (['log', 'info', 'warn', 'error', 'debug'] as const).map(m => vi.spyOn(console, m));
    const err = await validateRecipient(secret).catch(e => e);
    expect(err).toBeInstanceOf(RecipientError);
    expect(err.code).toBe('private-key');
    const secretBody = secret.slice('AGE-SECRET-KEY-1'.length, 40);
    expect(err.message).not.toContain(secretBody);
    expect(JSON.stringify(err)).not.toContain(secretBody);
    expect(String(err.stack)).not.toContain(secretBody);
    for (const s of spies) {
      for (const call of s.mock.calls) expect(JSON.stringify(call)).not.toContain(secretBody);
    }
  });

  it('rejects an identity embedded in a longer paste (e.g. whole key file)', async () => {
    const secret = await generateX25519Identity();
    const paste = `# created: 2026-11-23\n# public key: ${await identityToRecipient(secret)}\n${secret}\n`;
    await expect(validateRecipient(paste)).rejects.toMatchObject({ code: 'private-key' });
  });

  it('rejects post-quantum hybrid recipients (profile restricted to X25519)', async () => {
    const pq = await identityToRecipient(await generateHybridIdentity());
    await expect(validateRecipient(pq)).rejects.toMatchObject({ code: 'unsupported-age-type' });
  });

  it.each([
    ['', 'empty'],
    ['   ', 'empty'],
    ['ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIExample user@host', 'ssh-key'],
    ['npub1qqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqq', 'not-age-recipient'],
    ['age1abc', 'malformed'],
    ['x'.repeat(600), 'too-long'],
  ])('rejects %j with code %s', async (input, code) => {
    await expect(validateRecipient(input)).rejects.toMatchObject({ code });
  });

  it('rejects mixed case (invalid Bech32) and a corrupted checksum', async () => {
    const r = await freshRecipient();
    const mixed = r.slice(0, 10) + r.slice(10, 20).toUpperCase() + r.slice(20);
    await expect(validateRecipient(mixed)).rejects.toMatchObject({ code: 'mixed-case' });
    const last = r[r.length - 1];
    const corrupted = r.slice(0, -1) + (last === 'q' ? 'p' : 'q');
    await expect(validateRecipient(corrupted)).rejects.toMatchObject({ code: 'rejected-by-library' });
  });
});

describe('key ID presentation and comparison', () => {
  it('formats all 64 characters in groups', async () => {
    const id = await computeKeyId(await freshRecipient());
    const f = formatKeyId(id);
    expect(f.replace(/ /g, '')).toBe(id);
    expect(f.split(' ')).toHaveLength(16);
  });

  it('accepts only a full match, ignoring spaces/dashes/case', async () => {
    const id = await computeKeyId(await freshRecipient());
    expect(keyIdMatches(id, formatKeyId(id).toUpperCase())).toBe(true);
    expect(keyIdMatches(id, id.slice(0, 16))).toBe(false); // prefix only
    const flipped = id.slice(0, 63) + (id[63] === '0' ? '1' : '0');
    expect(keyIdMatches(id, flipped)).toBe(false);
  });
});

describe('recipient verification states (RF2)', () => {
  it('absent → invalid → unverified → confirmed', async () => {
    expect(await recipientStateFromInput('')).toEqual({ status: 'absent' });
    expect(await recipientStateFromInput('age1nope')).toMatchObject({ status: 'invalid', code: 'malformed' });
    const s = await recipientStateFromInput(await freshRecipient());
    expect(s.status).toBe('unverified');
    if (s.status !== 'unverified') throw new Error();
    const c = confirmRecipient(s, { method: 'full-key-id-entered', enteredKeyId: s.recipient.keyId });
    expect(c.status).toBe('confirmed');
    if (c.status !== 'confirmed') throw new Error();
    expect(Object.isFrozen(c.confirmation)).toBe(true);
    expect(Object.isFrozen(c.recipient)).toBe(true);
  });

  it('cannot be forced to confirmed with a mismatching fingerprint', async () => {
    const s = await recipientStateFromInput(await freshRecipient());
    const other = await computeKeyId(await freshRecipient());
    expect(() => confirmRecipient(s, { method: 'full-key-id-entered', enteredKeyId: other })).toThrow(KeyIdMismatchError);
  });

  it('cannot confirm an invalid recipient', async () => {
    const s = await recipientStateFromInput('age1nope');
    expect(() => confirmRecipient(s, { method: 'other-authenticated-channel' })).toThrow();
  });
});

describe('invite (RF9)', () => {
  it('round-trips through the URL fragment', async () => {
    const r = await freshRecipient();
    const caseRef = generateCaseRef();
    const inv = await createInvite({ recipient: r, caseRef, profile: ['packages', 'logcat', 'backup'], analystLabel: 'Lab A' });
    const url = inviteUrl('https://wafb.example/acquire', inv.fragment);
    expect(new URL(url).search).toBe(''); // never in the request line
    const parsed = await parseInvite(inviteFromHash(new URL(url).hash));
    expect(parsed.payload).toMatchObject({ recipient: r, caseRef, profile: ['packages', 'logcat', 'backup'] });
    expect(parsed.recipient.keyId).toBe(inv.keyId);
  });

  it('generates pseudonymous case references that pass validation', () => {
    for (let i = 0; i < 50; i++) expect(generateCaseRef()).toMatch(/^C-[2-9A-HJKMNP-TV-Z]{10}$/);
  });

  const enc = (o: unknown) =>
    Buffer.from(JSON.stringify(o)).toString('base64').replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');

  it.each<[string, (r: string) => unknown, string]>([
    ['unknown field', r => ({ v: 1, kind: 'wafb-invite', recipient: r, caseRef: 'C-ABC', profile: ['logcat'], extra: 1 }), 'unknown-field'],
    ['future version', r => ({ v: 2, kind: 'wafb-invite', recipient: r, caseRef: 'C-ABC', profile: ['logcat'] }), 'unsupported-version'],
    ['case ref with spaces / PII', r => ({ v: 1, kind: 'wafb-invite', recipient: r, caseRef: 'Mario Rossi', profile: ['logcat'] }), 'bad-case-ref'],
    ['unknown module', r => ({ v: 1, kind: 'wafb-invite', recipient: r, caseRef: 'C-ABC', profile: ['everything'] }), 'bad-profile'],
    ['empty profile', r => ({ v: 1, kind: 'wafb-invite', recipient: r, caseRef: 'C-ABC', profile: [] }), 'bad-profile'],
    ['bidi override in label', r => ({ v: 1, kind: 'wafb-invite', recipient: r, caseRef: 'C-ABC', profile: ['logcat'], analystLabel: 'Lab‮A' }), 'bad-label'],
    ['expired', r => ({ v: 1, kind: 'wafb-invite', recipient: r, caseRef: 'C-ABC', profile: ['logcat'], expiresAt: '2020-01-01T00:00:00Z' }), 'expired'],
  ])('rejects an invite with %s', async (_label, make, code) => {
    const r = await freshRecipient();
    await expect(parseInvite(enc(make(r)))).rejects.toMatchObject({ code });
  });

  it('rejects an invite carrying a private key, reporting the recipient sub-code', async () => {
    const secret = await generateX25519Identity();
    const e = await parseInvite(enc({ v: 1, kind: 'wafb-invite', recipient: secret, caseRef: 'C-ABC', profile: ['logcat'] })).catch(x => x);
    expect(e).toBeInstanceOf(InviteError);
    expect(e.code).toBe('bad-recipient');
    expect(e.recipientCode).toBe('private-key');
    expect(e.message).not.toContain(secret.slice(16, 40));
  });

  it('rejects garbage and oversized payloads', async () => {
    await expect(parseInvite(null)).rejects.toMatchObject({ code: 'missing' });
    await expect(parseInvite('!!!')).rejects.toMatchObject({ code: 'not-base64url' });
    await expect(parseInvite(enc('just a string'))).rejects.toMatchObject({ code: 'not-json' });
    await expect(parseInvite('A'.repeat(9000))).rejects.toMatchObject({ code: 'too-large' });
  });

  it('a substituted recipient yields a different key ID (detected only by out-of-band comparison)', async () => {
    const legit = await createInvite({ recipient: await freshRecipient(), caseRef: 'C-ABCDEF', profile: ['logcat'] });
    const evil = await createInvite({ recipient: await freshRecipient(), caseRef: 'C-ABCDEF', profile: ['logcat'] });
    const parsedEvil = await parseInvite(evil.encoded);
    // Syntactically perfect, same case reference: only the fingerprint differs.
    expect(parsedEvil.payload.caseRef).toBe(legit.payload.caseRef);
    expect(keyIdMatches(parsedEvil.recipient.keyId, legit.keyId)).toBe(false);
  });
});
